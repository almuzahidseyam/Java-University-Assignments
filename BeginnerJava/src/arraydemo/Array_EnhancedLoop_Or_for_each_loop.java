
package arraydemo;

public class Array_EnhancedLoop_Or_for_each_loop {
    
    public static void main(String[] args) {
        
        String[] names = new String[4];
        names[0] = "Anis";
        names[1] = "Muzahid";
        names[2] = "AL";
        names[3] = "Farhan";
        
        for (int i = 0; i < 4; i++) {
            System.out.println(names[i]);
        }
        
    }
}
