
package beginnerjava;

public class UnaryDemo {
    public static void main(String[] args) {
        
      //int x = 10;
      int x = -10;
      int result;
      
      result = +x; //unary plus
      System.out.println("result = "+result);
      
      result = -x; //unary minus
      System.out.println("result = "+result);
    }
}
