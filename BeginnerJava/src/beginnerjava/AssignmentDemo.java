
package beginnerjava;

public class AssignmentDemo {
    public static void main(String[] args) {
        
        int x = 3;
        int y = 2;
        
        x+=y;// x = x+y;
        System.out.println("x = "+x);// x = 3+2 =5
        
        x-=y; // x = x-y; =3
        System.out.println("x = "+x);
        
        x*=y; // x = x*y;
        System.out.println("x = "+x);
        
        x/=y;  // x = x/y;
        System.out.println("x = "+x);
        
        x%=y; // x = x%y;
        System.out.println("x = "+x);
        
    }
}
